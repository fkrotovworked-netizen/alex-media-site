// Builds what the assistant Алекс knows from the site's own texts: src/content.ts and src/cases.ts
// → worker/knowledge.js. Run after the texts change, then deploy the worker again:
//
//   npm run knowledge
//
// The modules are loaded through Vite (they use import.meta.env), so nothing is copied by hand
// and the assistant never knows more, or other, than the page says.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createServer } from 'vite';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const server = await createServer({ root, logLevel: 'error', server: { middlewareMode: true }, appType: 'custom' });
const { content: c } = await server.ssrLoadModule('/src/content.ts');
const { cases } = await server.ssrLoadModule('/src/cases.ts');
await server.close();

const lines = [];
const add = (...xs) => lines.push(...xs);
const flat = (a) => (Array.isArray(a) ? a.map((x) => (Array.isArray(x) ? x.map((y) => `— ${y}`).join('\n') : x)).join('\n') : a);

add('# Агентство', `Alex Media — ${c.footer.about}`, `Основатель: ${c.about.quote.name}, ${c.about.quote.role}.`);
add('', '## Цифры', ...c.stats.items.map((s) => `- ${s.prefix}${s.value}${s.suffix} — ${s.text}${s.confirm ? ' (цифра уточняется — не называть как точную)' : ''}`));
add('', '## Услуги', `- ${c.services.main.title} (основная специализация): ${c.services.main.text}`, ...c.services.items.map((s) => `- ${s.title}: ${s.text}`));
add('', '## AI-направления', ...c.ai.duties.map((d) => `- ${d.title}: ${d.text}`));
add(
  '',
  '## Цены',
  ...c.prices.items.map((p) => `- ${p.name}: ${p.price === 'индивидуально' ? 'индивидуально' : `от ${p.price} ${p.per}`.trim()}${p.confirm ? ' (цена предварительная, уточняется)' : ''}. ${p.text}.`),
  `- ${c.prices.budget}`,
  `- ${c.prices.pick.title} ${c.prices.pick.text}`
);
add(
  '',
  '## Аудит',
  c.audit.lead,
  ...c.audit.plans.map((p) => `- ${p.name}: ${p.price}${p.confirm ? ' (цена уточняется)' : ''}. ${p.format}.`),
  ...c.audit.rows.map((r) => `  · ${r.name}: экспресс — ${r.free === true ? 'да' : r.free === false ? 'нет' : r.free}; комплексный — ${r.paid === true ? 'да' : r.paid === false ? 'нет' : r.paid}`)
);
add('', '## Как работаем', ...c.process.stages.map((s, i) => `${i + 1}. ${s.name}: ${s.text} Результат: ${s.result}.`), c.process.note);
add('', '## Почему мы', ...c.about.reasons.map((r) => `- ${r.title}: ${r.text}`), `Слова основателя: «${c.about.quote.text}»`);
add(
  '',
  '## Кейсы (цифры — только из опубликованных статей, ссылки можно давать)',
  ...cases.map((k) => `- ${k.name} (${[k.niche, k.city].filter(Boolean).join(', ')}; ${k.channel}): ${k.value} ${k.unit} — ${k.note.replace(/\.+$/, "")}${k.anti ? ' (честный кейс, где не получилось)' : ''}. Статья: ${k.href}`)
);
add('', '## Отзывы', ...c.reviews.letters.map((l) => `- Благодарственное письмо: ${l.who}, ${l.company}`), ...c.reviews.videos.filter((v) => v.src).map((v) => `- Видеоотзыв: ${v.who}, ${v.company}`));
add('', '## Частые вопросы', ...c.faq.items.map((f) => `В: ${f.q}\nО: ${flat(f.a)}`));
add('', '## Контакты', ...c.footer.contacts.filter((x) => !x.confirm).map((x) => `- ${x.label}: ${x.value} ${x.href}`));

const text = lines.join('\n');
const services = c.final.services;
const out = `// Generated by scripts/build-knowledge.mjs from src/content.ts and src/cases.ts — do not edit by hand.
export const KNOWLEDGE = ${JSON.stringify(text)};
export const SERVICES = ${JSON.stringify(services)};
`;
await writeFile(path.join(root, 'worker', 'knowledge.js'), out);
console.log(`worker/knowledge.js: ${text.length} characters, ${cases.length} cases`);
process.exit(0);
